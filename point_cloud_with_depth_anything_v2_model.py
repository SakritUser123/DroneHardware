# Install from https://github.com/DepthAnything/Depth-Anything-V2

# Load the model and infer depth from an image
import cv2
import torch
from huggingface_hub import hf_hub_download

DEVICE = "cuda" if torch.cuda.is_available() else "cpu"


print("Model loaded")
from depth_anything_v2.dpt import DepthAnythingV2

# instantiate the model
model = DepthAnythingV2(encoder="vits", features=64, out_channels=[48, 96, 192, 384])

# load the weights
filepath = hf_hub_download(repo_id="depth-anything/Depth-Anything-V2-Small", filename="depth_anything_v2_vits.pth", repo_type="model")
state_dict = torch.load(filepath, map_location="cpu")
model.load_state_dict(state_dict)
model.eval()

from picamera2 import Picamera2
camera = Picamera2()

camera.configure(
    camera.create_preview_configuration(
        main={"format": 'RGB888', "size": (320, 240)}
        )
)
camera.start()
raw_img = camera.capture_array()
raw_img = cv2.cvtColor(raw_img, cv2.COLOR_RGB2BGR)
model = model.to(DEVICE)

depth = model.infer_image(raw_img) # HxW raw depth map in numpy
import matplotlib.pyplot as plt
plt.figure(figsize=(8,8))
plt.imshow(depth,cmap='Spectral')
plt.colorbar(label="Relative Depth")
plt.axis('off')
plt.show()
camera.stop()

import numpy as np

import open3d as o3d

h , w = depth.shape


fx = w / (2 * np.tan(np.radians(66/2)))

# square coordinates so vertical focal length equals horizontal focal length.
fy = h / (2 * np.tan(np.radians(41 / 2)))

cx = w/ 2

cy = h/ 2

Z = (depth-depth.min()) / (depth.max()-depth.min() + 1e-8)

Z = 1 - Z

# u contains x pixel positions all
# v contains the y pixel postiions all.

u , v = np.meshgrid(np.arrange(w), np.arange(h))

X = (u - cx) * Z / fx # calculates 3d horizontol position for each pixel.
Y = (v - cy) * Z / fy # calculates 3d vertical position for each pixel.

#creates all points by combing respectie x and y and z points it also reverses the y coordinates in order to match the chosen convention.
points = np.stack((X, -Y, Z), axis=-1).reshape(-1, 3) # creates each point in to a array [x,y,z]

colors = cv2.cvtColor(raw_img, cv2.COLOR_BGR2RGB) # gets original color
colors = colors.reshape(-1, 3) / 255.0 # creates them into colors from 0 to 255.

pcd = o3d.geometry.PointCloud() # creates empty point cloud.

pcd.points = o3d.utility.Vector3dVector(points) # adds all points to point cloud

pcd.colors = o3d.utility.Vector3dVector(colors) # adds all the respective colors to the cloud.

o3d.visualization.draw_geometries([pcd])  # displays the point cloud.




